# ============================================================

rows = []
seen = set()

for department, languages in DATA.items():

    base_examples = []

    for language, examples in languages.items():

        for example in examples:

            base_examples.append(
                (language, example)
            )

    department_count = 0
    attempts = 0

    while department_count < TARGET_PER_DEPARTMENT:

        attempts += 1

        if attempts > 100000:

            raise RuntimeError(
                f"Could not generate enough unique "
                f"examples for {department}"
            )

        language, base = random.choice(
            base_examples
        )

        prefix = random.choice(
            prefixes[language]
        )

        ending = random.choice(
            endings[language]
        )

        text = (
            prefix +
            base +
            ending
        )

        normalized = (
            text.strip()
            .lower()
        )

        if normalized in seen:
            continue

        seen.add(normalized)

        priority = choose_priority(
            text,
            department
        )

        rows.append([
            text.strip(),
            department,
            priority
        ])

        department_count += 1


